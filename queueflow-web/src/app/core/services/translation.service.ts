@Injectable({
  providedIn: 'root'
})
export class TranslationService {
  public currentLang = signal<Language>('en');

  constructor() {
    const saved = localStorage.getItem('queueflow-lang') as Language;
    if (saved === 'en' || saved === 'th') {
      this.currentLang.set(saved);
    } else {
      this.currentLang.set('en'); // Default is EN per requirement
    }
  }

  public t = computed(() => TRANSLATIONS[this.currentLang()]);

  public setLanguage(lang: Language) {
    this.currentLang.set(lang);
    localStorage.setItem('queueflow-lang', lang);
  }

  public toggleLanguage() {
    const next: Language = this.currentLang() === 'en' ? 'th' : 'en';
    this.setLanguage(next);
  }
}
